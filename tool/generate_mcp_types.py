#!/usr/bin/env python3
"""Generate MCP types from the pinned E2B schema; no network access needed."""
import json
from pathlib import Path
import subprocess
import sys

PIN = 'df6c368152b067512702fc677952c0fc4e13c2f0'
root = Path(sys.argv[1])
assert subprocess.check_output(['git', '-C', str(root), 'rev-parse', 'HEAD'], text=True).strip() == PIN
schema = json.loads((root / 'spec/mcp-server.json').read_text())
servers = schema['properties']
types = {'string': 'String', 'integer': 'int', 'number': 'num', 'boolean': 'bool', 'array': 'List<String>'}
def classname(key):
    return 'Mcp' + key[0].upper() + key[1:] + 'Config'

out = ['// Generated by tool/generate_mcp_types.py. Do not edit by hand.',
       '// ignore_for_file: non_constant_identifier_names',
       '// Source: E2B spec/mcp-server.json, commit ' + PIN + '.',
       "import 'mcp.dart';", '',
       '/// Names accepted by Template.addMcpServer in the pinned SDK.',
       'class McpServerName {',
       '  final String name;',
       '  const McpServerName._(this.name);',
       "  factory McpServerName.githubRepository(String repository) => McpServerName._('github/$repository');",
       *[f"  static const {key} = McpServerName._('{key}');" for key in servers],
       '  static const values = [' + ', '.join(servers) + '];',
       '  @override',
       '  bool operator ==(Object other) => other is McpServerName && name == other.name;',
       '  @override',
       '  int get hashCode => name.hashCode;',
       '  @override',
       '  String toString() => name;',
       '}', '',
       '/// Typed configurations for the MCP gateway bundled with E2B.',
       'class McpServer {']
for key in servers:
    out.append(f'  final {classname(key)}? {key};')
out += ['  final Map<String, GitHubMcpServerConfig> githubRepositories;', '  const McpServer({']
out += [f'    this.{key},' for key in servers]
out += ['    this.githubRepositories = const {},', '  });', '  Map<String, dynamic> toJson() => {']
out += [f"    if ({key} != null) '{key}': {key}!.toJson()," for key in servers]
out += ["    for (final entry in githubRepositories.entries) 'github/${entry.key}': entry.value.toJson(),", '  };', '}', '']
for key, config in servers.items():
    required = config.get('required', [])
    properties = config.get('properties', {})
    out.append(f'class {classname(key)} {{')
    for field, info in properties.items():
        out.append(f"  final {types[info['type']]}{'' if field in required else '?'} {field};")
    if properties:
        out.append(f'  const {classname(key)}({{')
        out += [f"    {'required ' if field in required else ''}this.{field}," for field in properties]
        out.append('  });')
    else:
        out.append(f'  const {classname(key)}();')
    out.append('  Map<String, dynamic> toJson() => {')
    for field in properties:
        condition = '' if field in required else f'if ({field} != null) '
        out.append(f"    {condition}'{field}': {field},")
    out += ['  };', '}', '']
Path('lib/src/mcp_generated.dart').write_text('\n'.join(out))

# Every declared field is exercised, including optional fields, numbers, arrays,
# boolean values and schema names with unusual capitalization.
tests = ['// Generated by tool/generate_mcp_types.py. Do not edit by hand.',
         "import 'package:e2b/e2b.dart';", "import 'package:test/test.dart';",
         'void main() {']
samples = {'string': 'value', 'integer': 42, 'number': 0.5,
           'boolean': True, 'array': ['a', 'b']}
for key, config in servers.items():
    values = {field: samples[info['type']] for field, info in config.get('properties', {}).items()}
    args = ', '.join(f'{field}: {json.dumps(value)}' for field, value in values.items())
    tests += [f"test('MCP schema {key}', () {{",
              f'final config = {classname(key)}({args});',
              f'expect(McpServer({key}: config).toJson(), {json.dumps({key: values})});',
              ]
    # Match the generated official TS declaration: required names without a
    # declared property (currently vectraAiRux.VECTRABASEURL) create no field.
    required_values = {field: values[field] for field in config.get('required', [])
                       if field in values}
    required_args = ', '.join(f'{field}: {json.dumps(value)}' for field, value in required_values.items())
    tests += [f'final minimal = {classname(key)}({required_args});' if config.get('properties')
              else f'final minimal = {classname(key)}();',
              f'expect(McpServer({key}: minimal).toJson(), {json.dumps({key: required_values})});',
              '});']
tests.append('}')
Path('test/mcp_generated_test.dart').write_text('\n'.join(tests))
