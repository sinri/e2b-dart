"""Generate typed JSON views for the schemas exported by the pinned JS SDK.
Requires Ruby's standard yaml/json libraries; no Python dependencies.
"""
import hashlib
import json
import pathlib
import re
import subprocess
import sys
import tempfile

checkout = pathlib.Path(sys.argv[1])
commit = subprocess.check_output(['git', '-C', str(checkout), 'rev-parse', 'HEAD'], text=True).strip()
if commit != 'df6c368152b067512702fc677952c0fc4e13c2f0':
    raise SystemExit('Unexpected upstream commit')
spec = checkout / 'spec/openapi.yml'
data = json.loads(subprocess.check_output(['ruby', '-ryaml', '-rjson', '-e',
    'puts JSON.generate(YAML.load_file(ARGV[0]))', str(spec)], text=True))
inventory = json.loads(pathlib.Path('docs/schema_inventory.json').read_text())
source = checkout / 'packages/js-sdk/src/api/schema.gen.ts'
if hashlib.sha256(source.read_bytes()).hexdigest() != inventory['sourceSha256']:
    raise SystemExit('Schema inventory source mismatch')
schemas = {name: data['components']['schemas'][name] for name in inventory['schemas']}
refs = set(re.findall(r'#/components/schemas/(\w+)', json.dumps(schemas)))
if refs - schemas.keys():
    raise SystemExit(f'Missing referenced schemas: {refs - schemas.keys()}')
# Ensure the selected YAML objects match the actual exported TS field inventory.
ts_components = source.read_text().split('export interface components {', 1)[1]
for name, schema in schemas.items():
    if 'properties' not in schema:
        continue
    start = re.search(r'^        ' + re.escape(name) + r': \{', ts_components, re.M)
    if start is None:
        raise SystemExit(f'Missing TS object: {name}')
    end = re.search(r'^        }(?:;| \| null;)', ts_components[start.end():], re.M)
    if end is None:
        raise SystemExit(f'Cannot delimit TS object: {name}')
    block = ts_components[start.end():start.end() + end.start()]
    fields = {m[1]: not bool(m[2]) for m in
              re.finditer(r'^            (\w+)(\?)?:', block, re.M)}
    expected = {key: key in schema.get('required', []) for key in schema['properties']}
    if fields != expected:
        raise SystemExit(f'TS/YAML property or required mismatch: {name}')
reserved = {'default', 'switch', 'case', 'class', 'enum', 'extends', 'final', 'const',
            'var', 'void', 'with', 'in', 'is', 'as', 'return', 'throw', 'catch', 'try',
            'super', 'this', 'new', 'null', 'true', 'false', 'get', 'set', 'static',
            'toJson', 'hashCode', 'runtimeType', 'noSuchMethod', 'toString'}
classes = {}

def cname(name):
    return 'ApiSchema' + name

def field(name):
    return name + 'Value' if name in reserved else name

def shape(s):
    if 'allOf' in s:
        if len(s['allOf']) != 1:
            raise ValueError('Unsupported allOf')
        return {**s['allOf'][0], **{k: v for k, v in s.items() if k != 'allOf'}}
    return s

def nullable(s):
    s = shape(s)
    return s.get('nullable', False) or ('$ref' in s and nullable(schemas[s['$ref'].split('/')[-1]]))

def typ(s, name):
    s = shape(s)
    if '$ref' in s:
        return cname(s['$ref'].split('/')[-1])
    if 'properties' in s or 'oneOf' in s:
        classes.setdefault(name, s)
        return cname(name)
    if not s: return 'Object?'
    t = s.get('type')
    if t == 'string': return 'String'
    if t in ('number', 'integer'): return 'num'
    if t == 'boolean': return 'bool'
    if t == 'array': return 'List<' + typ(s['items'], name + 'Item') + '>'
    if t == 'object' or 'additionalProperties' in s:
        p = s.get('additionalProperties')
        return 'Map<String, ' + (typ(p, name + 'Value') if isinstance(p, dict) else 'Object?') + '>'
    raise ValueError(f'Unsupported schema {name}: {s}')

def decode(s, name, value):
    s = shape(s)
    t = typ(s, name)
    if '$ref' in s:
        ref = s['$ref'].split('/')[-1]
        return decode(schemas[ref], ref, value)
    if 'properties' in s or 'oneOf' in s:
        return f'{t}.fromJson(Map<String, Object?>.from({value} as Map))'
    if s.get('type') == 'array':
        expr = decode(s['items'], name + 'Item', 'item')
        return f'List.unmodifiable(({value} as List).map((item) => {expr}))'
    if t.startswith('Map<'):
        p = s.get('additionalProperties')
        expr = decode(p, name + 'Value', 'item') if isinstance(p, dict) else 'item'
        return f'Map.unmodifiable(({value} as Map).map((key, item) => MapEntry(key as String, {expr})))'
    return f'{value} as {t}'

lines = ['// GENERATED by tool/generate_api_schema.py; do not edit.',
         '// e2b 2.55.0; JSON views validate field types when getters are read.',
         '// Optional absent and explicit null keys remain distinct in toJson().',
         '// ignore_for_file: non_constant_identifier_names', '',
         'abstract interface class ApiSchemaJson {',
         '  Map<String, Object?> toJson();', '}', '',
         '/// Supply an optional nullable field, including an explicit null.',
         'class ApiSchemaOptional<T> {', '  final T value;',
         '  const ApiSchemaOptional(this.value);', '}', '',
         'Object? _apiSchemaJson(Object? value) {',
         '  if (value is ApiSchemaJson) return _apiSchemaJson(value.toJson());',
         '  if (value is List) return value.map(_apiSchemaJson).toList();',
         '  if (value is Map) {',
         '    return value.map((key, item) =>',
         '      MapEntry(key as String, _apiSchemaJson(item)));', '  }',
         '  return value;', '}', '']
for name, s in schemas.items():
    t = typ(s, name)
    if name not in classes:
        lines += [f'typedef {cname(name)} = {t};', '']
processed = set()
while set(classes) - processed:
    name = next(n for n in classes if n not in processed)
    s = classes[name]
    processed.add(name)
    cls = cname(name)
    lines += [f'class {cls} implements ApiSchemaJson {{', '  final Map<String, Object?> _json;',
        f'  {cls}.fromJson(Map<String, Object?> json)',
        '      : _json = Map.unmodifiable(json);',
        '  @override', '  Map<String, Object?> toJson() => Map.of(_json);',
        '  bool containsKey(String key) => _json.containsKey(key);']
    if 'properties' in s:
        parameters = []
        entries = []
        for key, prop in s['properties'].items():
            nested = name + key[0].upper() + key[1:]
            t = typ(prop, nested)
            required = key in s.get('required', [])
            allows_null = nullable(prop) or t.endswith('?')
            arg = field(key)
            if required:
                parameters.append(f'required {t}{"?" if allows_null and not t.endswith("?") else ""} {arg}')
                value = arg
                condition = ''
            elif allows_null:
                parameters.append(f'ApiSchemaOptional<{t}{"" if t.endswith("?") else "?"}>? {arg}')
                value = arg + '.value'
                condition = f'if ({arg} != null) '
            else:
                parameters.append(f'{t}? {arg}')
                value = arg
                condition = f'if ({arg} != null) '
            entries.append(f'{condition}{json.dumps(key)}: _apiSchemaJson({value}),')
        lines += [f'  {cls}({{' + ', '.join(parameters) + '}) : this.fromJson({',
                  *['    ' + entry for entry in entries], '  });']
    if 'oneOf' in s:
        for tag, ref in s['discriminator']['mapping'].items():
            target = ref.split('/')[-1]
            lines += [f'  {cls}.{tag}({cname(target)} value) : this.fromJson(value.toJson());']
        discriminator = s['discriminator']['propertyName']
        lines += [f"  String get discriminator => _json['{discriminator}'] as String;"]
        for tag, ref in s['discriminator']['mapping'].items():
            target = ref.split('/')[-1]
            lines += [f'  {cname(target)}? get as{target} =>',
                f"      discriminator == '{tag}' ? {cname(target)}.fromJson(_json) : null;"]
    for key, prop in s.get('properties', {}).items():
        nested = name + key[0].upper() + key[1:]
        t = typ(prop, nested)
        is_nullable = key not in s.get('required', []) or nullable(prop)
        value = f"_json[{json.dumps(key)}]"
        expr = decode(prop, nested, value)
        lines += [f'  {t}{"?" if is_nullable and not t.endswith("?") else ""} get {field(key)} =>']
        if is_nullable:
            expr = f'{value} == null ? null : {expr}'
        lines += ['      ' + expr + ';']
    lines += ['}', '']
output = pathlib.Path('lib/src/api_schema_generated.dart')
rendered = '\n'.join(lines)
# Dart formatting remains a separate explicit step.
if '--check' in sys.argv:
    dart = sys.argv[sys.argv.index('--dart') + 1]
    with tempfile.TemporaryDirectory(prefix='e2b-schema-format-') as directory:
        temporary = pathlib.Path(directory) / 'schema.dart'
        temporary.write_text(rendered)
        subprocess.check_call([dart, 'format', str(temporary)], stdout=subprocess.DEVNULL)
        formatted = temporary.read_text()
    if output.read_text() != formatted:
        raise SystemExit('Generated schema differs')
else:
    output.write_text(rendered)
print(f'{len(schemas)} schema definitions; {len(classes)} JSON view classes')
