"""Generate callable Dart bindings for the pinned JS SDK's exported paths."""
import hashlib
import json
import pathlib
import re
import subprocess
import sys
import tempfile

checkout = pathlib.Path(sys.argv[1])
commit = subprocess.check_output(['git', '-C', str(checkout), 'rev-parse', 'HEAD'], text=True).strip()
if commit != 'df6c368152b067512702fc677952c0fc4e13c2f0':
    raise SystemExit('Unexpected upstream commit')
inventory = json.loads(pathlib.Path('docs/schema_inventory.json').read_text())
source = checkout / 'packages/js-sdk/src/api/schema.gen.ts'
if hashlib.sha256(source.read_bytes()).hexdigest() != inventory['sourceSha256']:
    raise SystemExit('Schema inventory source mismatch')
spec = json.loads(subprocess.check_output(['ruby', '-ryaml', '-rjson', '-e',
    'puts JSON.generate(YAML.load_file(ARGV[0]))', str(checkout / 'spec/openapi.yml')], text=True))
schemas = spec['components']['schemas']

def resolve(value):
    while '$ref' in value:
        parts = value['$ref'].split('/')[1:]
        value = spec
        for part in parts:
            value = value[part]
    return value

def typ(s):
    if '$ref' in s:
        name = s['$ref'].split('/')[-1]
        if name not in inventory['schemas']:
            raise ValueError(f'Unexported schema: {name}')
        return 'ApiSchema' + name
    t = s.get('type')
    if t == 'array': return f'List<{typ(s["items"])}>'
    return {'string': 'String', 'number': 'num', 'integer': 'num', 'boolean': 'bool'}[t]

def decode(s, value):
    if '$ref' in s:
        resolved = resolve(s)
        if 'properties' in resolved or 'oneOf' in resolved:
            return f'{typ(s)}.fromJson(Map<String, Object?>.from({value} as Map))'
        return decode(resolved, value)
    if s.get('type') == 'array':
        return f'List.unmodifiable(({value} as List).map((item) => {decode(s["items"], "item")}))'
    return f'{value} as {typ(s)}'

def identifier(name):
    words = re.split(r'[^a-zA-Z0-9]+', name)
    return words[0] + ''.join(w[:1].upper() + w[1:] for w in words[1:])

lines = ['// GENERATED by tool/generate_api_paths.py; do not edit.',
    '// e2b 2.55.0; callable path/method bindings, not cloud validation.',
    '// ignore_for_file: non_constant_identifier_names',
    "import 'api_endpoint_client.dart';", "import 'api_schema_generated.dart';",
    "import 'connection.dart';", '',
    'class ApiTypedResponse<T> {', '  final ApiResponse raw;', '  final T? data;',
    '  const ApiTypedResponse(this.raw, this.data);',
    '  Object? get error => raw.error;', '}', '', 'class ApiPaths {', '  ApiPaths._();']
ts_paths = source.read_text().split('export interface components {', 1)[0]
operations = []
for row in inventory['paths']:
    path = row['path']
    item = spec['paths'][path]
    for method in row['methods']:
        op = item[method]
        suffix = ''.join(identifier(seg.strip('{}'))[:1].upper() + identifier(seg.strip('{}'))[1:]
                         for seg in path.strip('/').split('/'))
        name = method + suffix
        cls = 'ApiPath' + name[:1].upper() + name[1:]
        operations.append((path, method, item, op, name, cls))
        lines += [f'  static const {name} = {cls}();']
lines += ['}', '']
for path, method, item, op, name, cls in operations:
    parameters = {}
    for entry in item.get('parameters', []) + op.get('parameters', []):
        p = resolve(entry)
        parameters[(p['in'], p['name'])] = p
    args = []
    groups = {'path': [], 'query': []}
    for (location, key), p in parameters.items():
        if location not in groups:
            raise ValueError(f'Unsupported parameter location: {location}')
        arg = identifier(key)
        required = p.get('required', False)
        args.append(f'{"required " if required else ""}{typ(p["schema"])}{"" if required else "?"} {arg}')
        groups[location].append(f'{"" if required else "if (" + arg + " != null) "}{json.dumps(key)}: {arg},')
    # Check YAML required flags against the actual exported TypeScript surface.
    path_start = re.search(r'^    ' + re.escape(json.dumps(path)) + r': \{', ts_paths, re.M)
    path_end = ts_paths.find('\n    };', path_start.end())
    path_block = ts_paths[path_start.end():path_end]
    method_start = re.search(r'^        ' + method + r': \{', path_block, re.M)
    method_end = path_block.find('\n        };', method_start.end())
    method_block = path_block[method_start.end():method_end]
    for location in ('path', 'query'):
        section = re.search(r'^                ' + location + r'\??: \{(.*?)^                };',
                            method_block, re.M | re.S)
        actual = {m[1]: not bool(m[2]) for m in re.finditer(
            r'^                    (\w+)(\?)?:', section[1] if section else '', re.M)}
        expected = {key: p.get('required', False) for (where, key), p in parameters.items()
                    if where == location}
        if actual != expected:
            raise ValueError(f'TS/YAML {location} required mismatch: {name}')
    body = resolve(op.get('requestBody', {}))
    ts_body = re.search(r'^            requestBody(\?)?: (\{|never)', method_block, re.M)
    if ts_body is None or bool(body) != (ts_body[2] == '{'):
        raise ValueError(f'TS/YAML request body mismatch: {name}')
    if body and body.get('required', False) != (not bool(ts_body[1])):
        raise ValueError(f'TS/YAML body required mismatch: {name}')
    if body:
        schema = body['content']['application/json']['schema']
        required = body.get('required', False)
        args.append(f'{"required " if required else ""}{typ(schema)}{"" if required else "?"} body')
    successes = []
    for status, response in op['responses'].items():
        if str(status).startswith('2'):
            r = resolve(response)
            successes.append(r.get('content', {}).get('application/json', {}).get('schema'))
    if any(s != successes[0] for s in successes):
        raise ValueError(f'Multiple success shapes: {name}')
    response_schema = successes[0]
    result = typ(response_schema) if response_schema else 'Object'
    args += ['RequestOptions? options', 'ApiQuerySerializer? querySerializer',
             'ApiPathSerializer? pathSerializer', 'ApiBodySerializer? bodySerializer',
             'List<ApiMiddleware> middleware = const []']
    lines += [f'class {cls} {{', f'  const {cls}();',
        f'  String get path => {json.dumps(path)};', f"  String get method => '{method.upper()}';",
        f'  Future<ApiTypedResponse<{result}>> call(ApiEndpointClient client, {{' + ', '.join(args) + '}) async {',
        '    final raw = await client.request(method, path,',
        '      pathParameters: {' + ''.join(groups['path']) + '},',
        '      query: {' + ''.join(groups['query']) + '},',
        *(['      body: body,'] if body else []), '      options: options,',
        '      querySerializer: querySerializer, pathSerializer: pathSerializer,',
        '      bodySerializer: bodySerializer, middleware: middleware);']
    expr = 'raw.data == null ? null : ' + decode(response_schema, 'raw.data') if response_schema else 'null'
    lines += [f'    return ApiTypedResponse<{result}>(raw, {expr});', '  }', '}', '']
# Other namespaces of the exported components interface.
components_text = source.read_text().split('export interface components {', 1)[1]
parameter_section = components_text.split('    parameters: {', 1)[1].split('\n    };', 1)[0]
for name, primitive in re.findall(r'^        (\w+): (string|number);', parameter_section, re.M):
    lines += [f'typedef ApiComponentParameter{name[:1].upper() + name[1:]} = ' +
              {'string': 'String', 'number': 'num'}[primitive] + ';']
header_section = re.search(r'^    headers: \{(.*?)^    };', components_text, re.M | re.S)[1]
for name, primitive in re.findall(r'^        (\w+): (string|number);', header_section, re.M):
    lines += [f'typedef ApiComponentHeader{name} = ' +
              {'string': 'String', 'number': 'num'}[primitive] + ';']
responses_section = components_text.split('    responses: {', 1)[1].split('\n    parameters:', 1)[0]
statuses = re.findall(r'^        (\d+): \{', responses_section, re.M)
if '    requestBodies: never;' not in components_text or '    pathItems: never;' not in components_text:
    raise ValueError('Unexpected populated component namespace')
lines += ['typedef ApiComponentRequestBodies = Never;',
          'typedef ApiComponentPathItems = Never;',
          '', 'class ApiComponentErrorResponse {',
    '  final ApiResponse raw;',
    '  ApiComponentErrorResponse(this.raw, int expectedStatus) {',
    '    if (raw.response.statusCode != expectedStatus) {',
    "      throw ArgumentError.value(raw.response.statusCode, 'status', 'Unexpected response status');",
    '    }', '  }',
    '  ApiSchemaError get content {',
    '    final value = raw.error;',
    '    if (value is! Map) {',
    "      throw const FormatException('Expected JSON error object');",
    '    }',
    '    return ApiSchemaError.fromJson(Map<String, Object?>.from(value));',
    '  }',
    '  Map<String, String> get headers => Map.unmodifiable(raw.response.headers);',
    '}', '']
for status in statuses:
    schema = resolve(spec['components']['responses'][status])['content']['application/json']['schema']
    if schema != {'$ref': '#/components/schemas/Error'}:
        raise ValueError(f'Unexpected shared response content: {status}')
    lines += [f'class ApiComponentResponse{status} extends ApiComponentErrorResponse {{',
              f'  ApiComponentResponse{status}(ApiResponse raw) : super(raw, {status});']
    if status == '429':
        lines += ['  num? get retryAfterSeconds => num.tryParse(headers["retry-after"] ?? "");']
    lines += ['}', '']
rendered = '\n'.join(lines)
output = pathlib.Path('lib/src/api_paths_generated.dart')
if '--check' in sys.argv:
    dart = sys.argv[sys.argv.index('--dart') + 1]
    with tempfile.TemporaryDirectory(prefix='e2b-paths-format-') as directory:
        temporary = pathlib.Path(directory) / 'paths.dart'
        temporary.write_text(rendered)
        subprocess.check_call([dart, 'format', str(temporary)], stdout=subprocess.DEVNULL)
        if output.read_text() != temporary.read_text():
            raise SystemExit('Generated paths differ')
else:
    output.write_text(rendered)
print(f'{len(operations)} callable path/method bindings generated')
